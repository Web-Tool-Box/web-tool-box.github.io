'use client';

import React, { useState } from 'react';
import { Copy, Check, Download, Bot } from 'lucide-react';

export default function RobotsTxtGenerator() {
  const [sitemapUrl, setSitemapUrl] = useState('https://webtoolbox.dev/sitemap.xml');
  const [blockAi, setBlockAi] = useState(false);
  const [disallowPaths, setDisallowPaths] = useState('/admin/\n/private/');
  const [copied, setCopied] = useState(false);

  const generated = `# robots.txt generated by WebToolBox
User-agent: *
${disallowPaths
  .split('\n')
  .filter(Boolean)
  .map((p) => `Disallow: ${p.trim()}`)
  .join('\n')}
Allow: /

${
  blockAi
    ? `# Restrict AI Scrapers
User-agent: GPTBot
Disallow: /

User-agent: ClaudeBot
Disallow: /

User-agent: CCBot
Disallow: /
`
    : ''
}Sitemap: ${sitemapUrl}`;

  const handleCopy = () => {
    navigator.clipboard.writeText(generated);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const blob = new Blob([generated], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'robots.txt';
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-6">
      <div className="grid grid-cols-1 sm:grid-cols-2 gap-4 p-5 rounded-2xl bg-slate-50 dark:bg-slate-950 border border-slate-200 dark:border-slate-800">
        <div>
          <label className="text-xs font-bold uppercase text-slate-500 block mb-1">
            XML Sitemap URL
          </label>
          <input
            type="text"
            value={sitemapUrl}
            onChange={(e) => setSitemapUrl(e.target.value)}
            className="w-full px-3 py-2 rounded-xl bg-white dark:bg-slate-900 border text-xs font-mono"
          />
        </div>

        <div className="flex items-center">
          <label className="flex items-center gap-2 cursor-pointer text-xs font-semibold text-slate-700 dark:text-slate-300">
            <input
              type="checkbox"
              checked={blockAi}
              onChange={(e) => setBlockAi(e.target.checked)}
              className="rounded text-indigo-600"
            />
            Block AI Crawlers (GPTBot, ClaudeBot, CCBot)
          </label>
        </div>

        <div className="sm:col-span-2">
          <label className="text-xs font-bold uppercase text-slate-500 block mb-1">
            Disallowed Paths (One per line)
          </label>
          <textarea
            value={disallowPaths}
            onChange={(e) => setDisallowPaths(e.target.value)}
            rows={3}
            className="w-full p-2.5 font-mono text-xs rounded-xl bg-white dark:bg-slate-900 border"
          />
        </div>
      </div>

      {/* Output File Box */}
      <div className="space-y-2">
        <div className="flex items-center justify-between">
          <label className="text-xs font-bold uppercase tracking-wider text-slate-500">
            robots.txt Content
          </label>
          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg font-semibold text-xs bg-slate-100 dark:bg-slate-800 hover:bg-slate-200 text-slate-700 dark:text-slate-300 transition-colors"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Copied' : 'Copy'}</span>
            </button>
            <button
              onClick={handleDownload}
              className="inline-flex items-center gap-1.5 px-4 py-1.5 rounded-lg font-semibold text-xs bg-indigo-600 hover:bg-indigo-700 text-white transition-colors"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download robots.txt</span>
            </button>
          </div>
        </div>
        <pre className="p-4 rounded-2xl bg-slate-100/70 dark:bg-slate-900 border border-slate-200 dark:border-slate-800 font-mono text-xs text-slate-800 dark:text-slate-200 overflow-x-auto">
          {generated}
        </pre>
      </div>
    </div>
  );
}
